func files(m map[string]string) Read {
	return func(p string) ([]byte, bool) {
		v, ok := m[p]
		return []byte(v), ok
	}
}

// Each recipe's command, files and image, with the version from the
// folder's own files, or the default (and it says which).
func TestResolve(t *testing.T) {
	for _, c := range []struct {
		fix              spec.Fix
		files            map[string]string
		image, from, cmd string
		writes           string
	}{
		{spec.Fix{Name: "a", Recipe: "npm", Path: "web"}, map[string]string{"web/.nvmrc": "v20.11.1\n"},
			"node:20-bookworm-slim", ".nvmrc", "npm install --package-lock-only --ignore-scripts", "package-lock.json"},
		{spec.Fix{Name: "a", Recipe: "npm", Path: "web"}, map[string]string{"web/package.json": `{"engines":{"node":">=18.17"},"packageManager":"npm@11.6.2"}`},
			"node:18-bookworm-slim", "package.json engines.node", "npm install -g npm@11.6.2", "package-lock.json"},
		{spec.Fix{Name: "a", Recipe: "npm", Path: "."}, map[string]string{"Dockerfile": "FROM docker.io/library/node:24-alpine AS build\n"},
			"node:24-bookworm-slim", "Dockerfile", "--ignore-scripts", "package-lock.json"},
		{spec.Fix{Name: "a", Recipe: "npm"}, nil, "node:" + DefaultNode + "-bookworm-slim", "default", "npm install", "package-lock.json"},
		{spec.Fix{Name: "a", Recipe: "pnpm", Path: "app"}, map[string]string{"app/package.json": `{"packageManager":"pnpm@9.12.0+sha512.abc"}`},
			"node:" + DefaultNode + "-bookworm-slim", "default", "corepack enable && pnpm install --lockfile-only --ignore-scripts", "pnpm-lock.yaml"},
		{spec.Fix{Name: "a", Recipe: "yarn"}, map[string]string{"yarn.lock": "# THIS IS AN AUTOGENERATED FILE.\n# yarn lockfile v1\n"},
			"node:" + DefaultNode + "-bookworm-slim", "default", "yarn install --ignore-scripts", "yarn.lock"},
		{spec.Fix{Name: "a", Recipe: "yarn"}, map[string]string{"package.json": `{"packageManager":"yarn@4.5.0"}`},
			"node:" + DefaultNode + "-bookworm-slim", "default", "yarn install --mode update-lockfile", "yarn.lock"},
		{spec.Fix{Name: "a", Recipe: "go", Path: "api"}, map[string]string{"api/go.mod": "module x\n\ngo 1.23.4\n"},
			"golang:1.23.4", "go.mod", "go mod tidy", "go.mod go.sum"},
		{spec.Fix{Name: "a", Recipe: "go"}, map[string]string{"go.mod": "module x\n\ngo 1.24\n\ntoolchain go1.25.1\n"},
			"golang:1.25.1", "go.mod toolchain", "go mod tidy", "go.mod go.sum"},
		{spec.Fix{Name: "a", Recipe: "uv"}, map[string]string{".python-version": "3.13\n"},
			"ghcr.io/astral-sh/uv:python3.13-bookworm-slim", ".python-version", "uv lock", "uv.lock"},
		{spec.Fix{Name: "a", Recipe: "poetry"}, map[string]string{"pyproject.toml": "[project]\nrequires-python = \">=3.11\"\n"},
			"python:3.11-slim", "pyproject.toml requires-python", "poetry lock", "poetry.lock"},
		{spec.Fix{Name: "a", Recipe: "pip-tools"}, map[string]string{"Dockerfile": "FROM python:3.10-slim\n"},
			"python:3.10-slim", "Dockerfile", "pip-compile", "requirements.txt"},
		{spec.Fix{Name: "a", Image: "node:20", Command: "npm i --package-lock-only", Writes: []string{"package-lock.json"}}, nil,
			"node:20", "declared", "npm i --package-lock-only", "package-lock.json"},
	} {
		p, err := Resolve(c.fix, files(c.files), 0)
		if err != nil {
			t.Errorf("%+v: %v", c.fix, err)
			continue
		}
		if p.Image != c.image || p.ImageFrom != c.from || !strings.Contains(p.Command, c.cmd) || strings.Join(p.Writes, " ") != c.writes {
			t.Errorf("%s %v: got %s (%s) %q %v", c.fix.Recipe, c.files, p.Image, p.ImageFrom, p.Command, p.Writes)
		}
		if p.Timeout != spec.DefaultFixTimeout*time.Second {
			t.Errorf("timeout %s", p.Timeout)
		}
	}
	// A version in packageManager that is not a version never reaches the shell.
	p, _ := Resolve(spec.Fix{Name: "a", Recipe: "npm"}, files(map[string]string{"package.json": `{"packageManager":"npm@1; rm -rf /"}`}), 0)
	if strings.Contains(p.Command, "rm -rf") {
		t.Fatalf("command %q", p.Command)
	}
	// The timeout is the fix's, at most the platform's.
	p, _ = Resolve(spec.Fix{Name: "a", Recipe: "go", Timeout: 1800}, nil, 45*time.Minute)
	if p.Timeout != 1800*time.Second {
		t.Fatalf("timeout %s", p.Timeout)
	}
	p, _ = Resolve(spec.Fix{Name: "a", Recipe: "go", Timeout: 3000}, nil, 10*time.Minute)
	if p.Timeout != 10*time.Minute {
		t.Fatalf("capped timeout %s", p.Timeout)
	}
}

